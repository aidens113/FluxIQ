import type { AssistantHiddenEndpoint, AssistantToolCatalogFile, AssistantToolEntry } from "@fluxiq/contracts/program-api-inputs";
import { assistantToolOf } from "./tool.ts";
import { assistantToolName } from "./tool-name.ts";
import type { AssistantEndpointSummary } from "./types.ts";

/** How to regenerate the file, as its header and the drift test say it. */
export const ASSISTANT_TOOLS_REGENERATE = "set FLUXIQ_REGENERATE_ASSISTANT_TOOLS=1 and run `pnpm exec vitest run src/programs/_shared/assistant` in packages/fluxiq";

/**
 * Source of `platform/iam/catalog/generated/assistant-tools.generated.json`:
 * every declared tool (its derived consequence and its input's JSON Schema)
 * and every hidden endpoint with its reason, each sorted by name. Undeclared
 * endpoints are left out; the parity test names them. It is data for review
 * and drift checking, not code: the assistant reads its tools from the live
 * registry (`AssistantToolCatalog`), so nothing imports this file.
 */
export function renderAssistantToolsModule(endpoints: readonly AssistantEndpointSummary[]): string {
  const tools: AssistantToolEntry[] = [];
  const hidden: AssistantHiddenEndpoint[] = [];
  for (const endpoint of endpoints) {
    const declaration = endpoint.assistant;
    if (declaration === undefined) continue;
    const name = assistantToolName(endpoint.programId, endpoint.endpoint);
    if ("hidden" in declaration) {
      hidden.push({ name, programId: endpoint.programId, endpoint: endpoint.endpoint, reason: declaration.hidden.trim() });
      continue;
    }
    const tool = assistantToolOf(endpoint);
    if (tool === undefined) continue;
    tools.push({ name, programId: tool.programId, endpoint: tool.endpoint, summary: tool.summary, phrases: tool.phrases, consequence: tool.consequence, contextArgs: tool.contextArgs, inputSchema: tool.inputSchema });
  }
  const catalog: AssistantToolCatalogFile = { tools: tools.sort(byName), hidden: hidden.sort(byName) };
  const file = {
    $comment: `GENERATED by renderAssistantToolsModule (${ASSISTANT_TOOLS_REGENERATE}). Do not edit; regenerate instead. Every program API endpoint the panel assistant may call, and every one it is never offered, with why.`,
    ...catalog
  };
  return `${JSON.stringify(file, null, 2)}\n`;
}

function byName(a: { name: string }, b: { name: string }): number {
  if (a.name < b.name) return -1;
  return a.name > b.name ? 1 : 0;
}
