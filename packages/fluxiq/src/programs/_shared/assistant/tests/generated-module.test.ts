// The generated assistant catalog: deterministic output, and the checked-in file current with the live registry.
import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { listFlowsInput } from "@fluxiq/contracts/program-api-inputs";
import { createGlobalProgramRuntime } from "../../runtime.ts";
import { ASSISTANT_TOOLS_REGENERATE, renderAssistantToolsModule, type AssistantEndpointSummary } from "../index.ts";

// A CRLF checkout of the same file is current; line endings are not content.
function withLfLineEndings(text: string): string {
  return text.replaceAll("\r\n", "\n");
}

const generatedPath = new URL("../../../../platform/iam/catalog/generated/assistant-tools.generated.json", import.meta.url);

const LIST: AssistantEndpointSummary = {
  programId: "automation-studio", endpoint: "list-flows", permission: "programs.read", classification: "read",
  assistant: { input: listFlowsInput, summary: "Lists the Flows in a project.", phrases: ["show my flows"], contextArgs: { projectId: "projectId" } }
};
const HIDDEN: AssistantEndpointSummary = { programId: "automation-studio", endpoint: "record-performance", permission: "programs.write", classification: "authoring", assistant: { hidden: "Internal measurements." } };
const BARE: AssistantEndpointSummary = { programId: "automation-studio", endpoint: "bare-endpoint", permission: "programs.read", classification: "read" };

describe("renderAssistantToolsModule", () => {
  it("renders tools and hidden endpoints sorted by name, whatever the registration order, and leaves out undeclared ones", () => {
    const rendered = renderAssistantToolsModule([HIDDEN, BARE, LIST]);
    expect(renderAssistantToolsModule([LIST, HIDDEN, BARE])).toBe(rendered);
    expect(rendered).toContain("\"name\": \"automation-studio__list-flows\"");
    expect(rendered).toContain("\"consequence\": \"read\"");
    expect(rendered).toContain("\"reason\": \"Internal measurements.\"");
    expect(rendered).toContain("\"required\": [");
    expect(rendered).not.toContain("bare-endpoint");
    expect(JSON.parse(rendered).$comment).toMatch(/^GENERATED by renderAssistantToolsModule/u);
  });
});

describe("assistant-tools.generated.json", () => {
  it("is current with the live registry", () => {
    const rendered = renderAssistantToolsModule(createGlobalProgramRuntime().api.endpoints());
    if (process.env.FLUXIQ_REGENERATE_ASSISTANT_TOOLS === "1") writeFileSync(generatedPath, rendered);
    expect(withLfLineEndings(readFileSync(generatedPath, "utf8")), `assistant-tools.generated.json drifted: ${ASSISTANT_TOOLS_REGENERATE}`).toBe(withLfLineEndings(rendered));
  });
});
