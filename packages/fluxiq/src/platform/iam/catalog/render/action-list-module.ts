/** Renders a generated module exporting one frozen string array. */
export function renderIamActionListModule(exportName: string, regenerate: string, actions: readonly string[]): string {
  const items = actions.map((action) => `  ${JSON.stringify(action)}`).join(",\n");
  return [
    `// GENERATED by ${regenerate}. Do not edit; regenerate instead.`,
    `export const ${exportName}: readonly string[] = Object.freeze([`,
    items,
    "]);",
    ""
  ].join("\n");
}
