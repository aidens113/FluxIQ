import { CLOUD_PROJECT_LABEL } from "../project-label.ts";
import { toYaml, type YamlValue } from "./to-yaml.ts";

const LABELS = { [CLOUD_PROJECT_LABEL]: "${FLUXIQ_CLOUD_PROJECT}" };

/**
 * The rehearsal's stand-ins, a third Compose file present only when the
 * config turns a sink on: Mailpit (SMTP on mailpit:1025, its web view and API
 * on a loopback port) and stripe/stripe-mock (on stripe-mock:12111). Both
 * join the edge network, where Core reaches them by name, exactly as it
 * would reach a relay or Stripe by theirs.
 */
export function renderSinks(sinks: { mail: boolean; payments: boolean }): string {
  const services: Record<string, YamlValue> = {};
  const dependsOn: Record<string, YamlValue> = {};
  if (sinks.mail) {
    services.mailpit = {
      image: "${MAILPIT_IMAGE}",
      labels: LABELS,
      environment: { MP_MAX_MESSAGES: "5000" },
      ports: ["127.0.0.1:${MAILPIT_UI_PORT}:8025"],
      networks: ["edge"],
      security_opt: ["no-new-privileges:true"],
      restart: "unless-stopped"
    };
    dependsOn.mailpit = { condition: "service_started" };
  }
  if (sinks.payments) {
    services["stripe-mock"] = {
      image: "${STRIPE_MOCK_IMAGE}",
      labels: LABELS,
      networks: ["edge"],
      security_opt: ["no-new-privileges:true"],
      restart: "unless-stopped"
    };
    dependsOn["stripe-mock"] = { condition: "service_started" };
  }
  services.fluxiq = { depends_on: dependsOn };
  return `${HEADER}${toYaml({ services })}`;
}

const HEADER = `# Generated by @fluxiq/cloud for a local rehearsal: the mail and payments
# sinks. A production config turns them off, and this file is not written.
`;
