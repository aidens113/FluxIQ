import { CLOUD_PROJECT_LABEL } from "../project-label.ts";
import { toYaml, type YamlValue } from "./to-yaml.ts";

const LABELS = { [CLOUD_PROJECT_LABEL]: "${FLUXIQ_CLOUD_PROJECT}" };

/**
 * The override Compose reads after deploy/compose/service.compose.yml: the
 * project label on every service, network, volume and the built image, the
 * build context, and where the secrets come from.
 *
 * Core reads its secrets from `/run/secrets`, as the base file says, but here
 * that folder is the `<project>_secrets` volume the driver fills from the
 * secret files: each file owned by Core's user (uid 1000) and readable only by
 * it, which Core's private-file check on the host keyring requires. Compose's
 * own file secrets cannot promise that (outside Swarm they are bind mounts,
 * and Docker Desktop shows Windows files as root's with mode 0777), and its
 * variable-sourced secrets are refused on a read-only service. The base
 * file's secrets are therefore cleared (`!reset`). The volume is `external`:
 * the driver creates, fills and removes it, by the project label.
 *
 * The file is the same for every config; its values come from compose.env.
 */
export function renderOverride(): string {
  const override: Record<string, YamlValue> = {
    services: {
      fluxiq: {
        build: { context: "${FLUXIQ_BUILD_CONTEXT}", dockerfile: "deploy/docker/Dockerfile", labels: LABELS },
        labels: LABELS,
        secrets: { yamlTag: "!reset", value: [] },
        volumes: ["secrets:/run/secrets:ro"]
      },
      caddy: { labels: LABELS }
    },
    networks: { edge: { labels: LABELS }, provisioning: { labels: LABELS } },
    volumes: {
      "fluxiq-data": { labels: LABELS },
      "caddy-data": { labels: LABELS },
      "caddy-config": { labels: LABELS },
      secrets: { external: true, name: "${FLUXIQ_CLOUD_PROJECT}_secrets" }
    },
    secrets: { yamlTag: "!reset", value: {} }
  };
  return `${HEADER}${toYaml(override)}`;
}

const HEADER = `# Generated by @fluxiq/cloud (fluxiq-cloud up or render). Do not edit: change
# fluxiq-cloud.config.json and render again. Read after
# deploy/compose/service.compose.yml; values come from compose.env. The
# secrets volume is filled by fluxiq-cloud up (deployment.json says how).
`;
