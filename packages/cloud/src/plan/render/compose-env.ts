import type { CloudConfig } from "../../config/index.ts";
import { toEnvFile } from "./to-env-file.ts";

/**
 * compose.env: the values Compose interpolates into the Compose files
 * (`docker compose --env-file`): the project, the image, the source
 * checkout, the provisioning network and the ports. Nothing in it is
 * secret, and it never reaches a container. Secrets come from FLUXIQ_SECRET_*
 * variables on the compose process instead (renderOverride says why).
 */
export function renderComposeEnv(config: CloudConfig, coreImage: string, provisioningNetwork: string | null, environments = false): string {
  const values: [string, string][] = [
    ["FLUXIQ_CLOUD_PROJECT", config.project],
    ["FLUXIQ_IMAGE", coreImage],
    ["FLUXIQ_BUILD_CONTEXT", config.sourceRoot],
    ["CADDY_IMAGE", config.images.caddy],
    ["CADDYFILE", "../caddy/Caddyfile"],
    ["FLUXIQ_ENV_FILE", `../env/${config.mode}.env`],
    ["FLUXIQ_HTTP_PORT", String(config.ports.http)],
    ["FLUXIQ_HTTPS_PORT", String(config.ports.https)]
  ];
  if (provisioningNetwork !== null) {
    values.push(["FLUXIQ_PROVISIONING_NETWORK", provisioningNetwork], ["FLUXIQ_PROVISIONING_SUBNET", config.provisioning.subnet], ["FLUXIQ_PROVISIONING_ADDRESS", config.provisioning.address]);
  }
  // The engine socket's group, which up finds and passes to Compose itself; 0 (root's group, Docker Desktop's) when run by hand.
  if (environments) values.push(["FLUXIQ_DOCKER_SOCKET_GROUP", "0"]);
  if (config.sinks.mail) values.push(["MAILPIT_IMAGE", config.images.mailpit], ["MAILPIT_UI_PORT", String(config.sinks.mailUiPort)]);
  if (config.sinks.payments) values.push(["STRIPE_MOCK_IMAGE", config.images.stripeMock]);
  return toEnvFile(["Generated by @fluxiq/cloud from fluxiq-cloud.config.json. Compose interpolation values only;", "no secret is in this file, and it never reaches a container."], values);
}
