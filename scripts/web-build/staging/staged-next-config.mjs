// The `next.config.ts` a staged build runs with: Core's own config, copied
// beside it as `next.config.core.ts` and called unchanged, plus a Turbopack
// root at the filesystem root the Core checkout sits on.
//
// The root is the one thing a staged build needs that Core's in-place build
// does not. The staged `node_modules` are links into the Core checkout's
// installation, and Turbopack resolves a link to its real path, so every
// package the panel imports lives outside the staged directory; a root that
// holds both is the filesystem root they share. Next transpiles this file and
// loads the relative `.ts` import through its own require hook.

import path from "node:path";

/** The name Core's own config is copied under, beside the wrapper. */
const CORE_CONFIG = "next.config.core.ts";

/**
 * @param {string} repoRoot the Core checkout
 * @returns {string} the wrapper's source text
 */
export function stagedNextConfig(repoRoot) {
  const root = path.parse(path.resolve(repoRoot)).root;
  return [
    "// Generated by FluxIQ Core's scripts/web-build for a staged build. Core's own",
    `// config is ${CORE_CONFIG}; this adds only the Turbopack root.`,
    'import type { NextConfig } from "next";',
    `import core from "./${CORE_CONFIG}";`,
    "",
    "type Context = { defaultConfig: NextConfig };",
    "type CoreConfig = NextConfig | ((phase: string, context: Context) => NextConfig | Promise<NextConfig>);",
    "",
    "export default async function stagedNextConfig(phase: string, context: Context): Promise<NextConfig> {",
    "  const declared = core as CoreConfig;",
    '  const config = typeof declared === "function" ? await declared(phase, context) : declared;',
    `  return { ...config, turbopack: { ...config.turbopack, root: ${JSON.stringify(root)} } };`,
    "}",
    ""
  ].join("\n");
}
